import assert from "node:assert/strict";
import fs from "node:fs";
import { AmbientOpportunity } from "./ambient-opportunity.js";
const values=new URL("../../../../values/player-voice-library-300-review-v1/",import.meta.url);
const read=name=>JSON.parse(fs.readFileSync(new URL(name,values),"utf8"));
const policy=read("policy.json"), groups=read("groups.json");
const lines=["lines-001-075.json","lines-076-150.json","lines-151-225.json","lines-226-300.json"].flatMap(read);
assert.equal(lines.length,300);assert.equal(new Set(lines.map(l=>l.id)).size,300);assert.equal(new Set(lines.map(l=>l.text)).size,300);
assert.equal(lines.filter(l=>l.group==="random").length,24);
for(const group of groups)assert.equal(lines.filter(l=>l.group===group.id).length,group.type==="random"?24:12);
for(const line of lines){assert.equal(line.decision,"pending");assert.ok(line.text.match(/[A-Za-z]+(?:'[A-Za-z]+)*/g).length<=9);}
assert.equal(lines.find(l=>l.id==="L193").requires.daylight,true);
const minute=60000, make=()=>new AmbientOpportunity(policy.random,()=>0.5);
const timer=make();
assert.equal(timer.advance(30*minute,{paused:true}),"not-due");assert.equal(timer.activeMs,0);
assert.equal(timer.advance(30*minute,{visible:false}),"not-due");assert.equal(timer.activeMs,0);
assert.equal(timer.advance(30*minute,{gameplay:false}),"not-due");assert.equal(timer.activeMs,0);
assert.equal(timer.advance(29*minute),"not-due");assert.equal(timer.advance(minute,{npcDialogue:true}),"held-other-voice");
assert.equal(timer.advance(0,{speechBusy:true}),"held-other-voice");
assert.equal(timer.advance(0,{narration:true}),"held-other-voice");
assert.equal(timer.advance(0,{danger:true}),"held-danger");
assert.equal(timer.advance(0,{pendingEvent:true}),"held-event");
assert.equal(timer.advance(0,{quietMs:19999}),"held-quiet-gap");
assert.equal(timer.advance(0,{sincePlayerMs:89999}),"held-quiet-gap");
assert.equal(timer.advance(0,{quietMs:20000,sincePlayerMs:90000}),"eligible");
timer.markStarted();assert.equal(timer.nextDueMs,60*minute);
assert.equal(timer.advance(29*minute),"not-due");
const missed=make();assert.equal(missed.advance(33*minute),"missed-window-no-backlog");
assert.equal(missed.nextDueMs,63*minute);assert.equal(missed.advance(0),"not-due");
const minimum=new AmbientOpportunity(policy.random,()=>0),maximum=new AmbientOpportunity(policy.random,()=>1);
assert.equal(minimum.nextDueMs,27*minute);assert.equal(maximum.nextDueMs,33*minute);
assert.ok(policy.priority.npc>policy.priority.event && policy.priority.event>policy.priority.random);
assert.equal(policy.speech.playerInterrupts,false);
const attack=t=>policy.music.floorGain+(1-policy.music.floorGain)*Math.exp(-t/policy.music.attackTimeConstantMs);
assert.ok(attack(0)>attack(300)&&attack(300)>attack(900));assert.ok(attack(900)>policy.music.floorGain);
const release=(t,start)=>1+(start-1)*Math.exp(-t/policy.music.releaseTimeConstantMs);
assert.equal(release(0,attack(900)),attack(900));assert.ok(release(2400,attack(900))>0.95);
console.log("LEO_300_REVIEW_CONTRACT_OK: unique scripts, exact counts, limits, daytime gate, inactive time, NPC/narration/event priority, quiet gaps, missed-window discard and smooth envelope.");
