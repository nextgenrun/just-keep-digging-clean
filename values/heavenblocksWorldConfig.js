export function getHeavenblockWorldRegion(regionId) {
  return HEAVENBLOCKS_WORLD_CONFIG.regions.find((entry) => entry.id === regionId) || null;
}

export function getHeavenblockCellDescriptor(tileX, tileY) {
  for (const entry of HEAVENBLOCKS_WORLD_CONFIG.regions) {
    const localX = tileX - entry.leftTile;
    const localY = tileY - entry.topTile;
    if (
      localX < 0
      || localY < 0
      || localX >= entry.widthTiles
      || localY >= entry.heightTiles
    ) continue;
    return {
      region: entry,
      localX,
      localY,
      marker: entry.layoutRows[localY]?.[localX] || HEAVENBLOCK_CELL_MARKERS.AIR,
    };
  }
  return null;
}
