const TILE_SIZE_PX = 94;
const REGION_WIDTH_TILES = 21;
const REGION_HEIGHT_TILES = 12;

const freeze = (value) => {
  if (!value || typeof value !== "object" || Object.isFrozen(value)) return value;
  Object.freeze(value);
  Object.values(value).forEach(freeze);
  return value;
};

const point = (tx, ty) => ({ tx, ty });

function region({
  id,
  label,
  levelId,
  leftTile,
  topTile,
  color,
  layoutRows,
  arrivalLocal,
  entryShaftLocal,
  entryDirection,
  returnAltarLocal,
  arcVaultLocal,
  coreLocal,
  surfaceGate,
  surfaceReturn,
  requiredUpgradeId = null,
  partId,
  partLabel,
  vaultId,
  componentAssetKey,
  heartAssetKey,
  heartAssetPath,
  backdropKey,
  backdropPath,
  tileStyle,
  materialPalette,
  materialHealthScale,
  coreHealth,
}) {
  return {
    id,
    label,
    levelId,
    leftTile,
    topTile,
    widthTiles: REGION_WIDTH_TILES,
    heightTiles: REGION_HEIGHT_TILES,
    displayWidthPx: REGION_WIDTH_TILES * TILE_SIZE_PX,
    displayHeightPx: REGION_HEIGHT_TILES * TILE_SIZE_PX,
    color,
    layoutRows,
    arrival: point(leftTile + arrivalLocal.tx, topTile + arrivalLocal.ty),
    entryShaft: point(leftTile + entryShaftLocal.tx, topTile + entryShaftLocal.ty),
    entryDirection,
    returnAltar: point(leftTile + returnAltarLocal.tx, topTile + returnAltarLocal.ty),
    arcVault: point(leftTile + arcVaultLocal.tx, topTile + arcVaultLocal.ty),
    core: point(leftTile + coreLocal.tx, topTile + coreLocal.ty),
    surfaceGate,
    surfaceReturn,
    requiredUpgradeId,
    partId,
    partLabel,
    vaultId,
    componentAssetKey,
    heartAssetKey,
    heartAssetPath,
    backdropKey,
    backdropPath,
    tileStyle,
    materialPalette,
    materialHealthScale,
    coreHealth,
    portalAssetKey: levelId === 1
      ? "v11-sky-island-level-1-portal"
      : "v11-sky-island-level-2-portal",
  };
}

