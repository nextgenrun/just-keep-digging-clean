"""Dump the UE 5.8 Python surface needed for a scripted IK retarget proof."""

from __future__ import annotations

import inspect
import json
from pathlib import Path

import unreal


PROJECT_DIR = Path(unreal.Paths.project_dir())
REPORT_PATH = PROJECT_DIR / "SourceAssets" / "unreal-retarget-api.json"


def public_members(value: object) -> list[str]:
    return sorted(name for name in dir(value) if not name.startswith("_"))


tokens = ("ikrig", "retarget", "animationlibrary", "animsequence", "fbximport")
class_names = sorted(name for name in dir(unreal) if any(token in name.lower() for token in tokens))

focus_names = [
    "IKRigDefinition",
    "IKRigController",
    "IKRetargeter",
    "IKRetargeterController",
    "IKRetargetBatchOperation",
    "IKRetargetBatchOperationContext",
    "IKRetargetAutoGeneratedAssets",
    "IKRetargetFactory",
    "IKRigDefinitionFactory",
    "AssetImportTask",
    "FbxImportUI",
    "AnimSequence",
    "AnimSequenceExporterFBX",
    "EditorAssetLibrary",
]

focus = {}
for name in focus_names:
    value = getattr(unreal, name, None)
    if value is not None:
        focus[name] = public_members(value)

REPORT_PATH.write_text(
    json.dumps(
        {
            "unreal_version": unreal.SystemLibrary.get_engine_version(),
            "matching_classes": class_names,
            "focus": focus,
        },
        indent=2,
    ),
    encoding="utf-8",
)

unreal.log(f"RETARGET_API_PROBE_OK classes={len(class_names)} report={REPORT_PATH}")
