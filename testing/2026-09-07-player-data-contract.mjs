import assert from 'node:assert/strict';
import { SessionRecorder, safeSessionFields } from '../systems/telemetry/SessionRecorder.js';
import { PlayerDataOutbox } from '../systems/telemetry/PlayerDataOutbox.js';
import { PlayerDataTransport } from '../systems/telemetry/PlayerDataTransport.js';
import { PLAYER_SESSION_LOGGING as C } from '../values/playerSessionLogging.js';
let clock = 0;
const recorder = new SessionRecorder({ now: () => clock, sessionId: crypto.randomUUID() });
recorder.setState({ phase: 'gameplay', scene: 'PlayScene' });
for (clock = 1000; clock <= 40000; clock += 1000) recorder.account();
assert.equal(recorder.totals.gameplay, 30000);
assert.equal(recorder.totals.idle, 10000);
recorder.input('moveLeft', true);
const before = recorder.totals.gameplay;
for (let n = 0; n < 45; n++) { clock += 1000; recorder.account(); }
assert.equal(recorder.totals.gameplay - before, 45000, 'held input stays active');
recorder.setState({ focused: false });
assert.equal(recorder.held.size, 0, 'focus loss releases held inputs');
const active = recorder.totals.gameplay;
clock += 1000; recorder.account();
assert.equal(recorder.totals.gameplay, active);
assert.equal(recorder.totals.unfocused, 1000);
recorder.setState({ focused: true });
clock += C.unknownGapAfterMs + 1; recorder.account();
assert.equal(recorder.totals.unknown, C.unknownGapAfterMs + 1, 'suspended interval is not invented playtime');
assert.deepEqual(safeSessionFields({ password: 'secret', text: 'typed', action: 'dig', state: { ownerToken: 'private', gp: 3 } }), { action: 'dig', state: { gp: 3 } });
for (let n = 0; n < C.maxMemoryEvents + 10; n++) recorder.record('input_down', { action: 'dig' });
assert.equal(recorder.events.length, C.maxMemoryEvents);
assert.ok(recorder.dropped > 0);
const batch = recorder.takeBatch(crypto.randomUUID(), 'test');
assert.ok(batch.events.length <= C.maxBatchEvents);
assert.ok(new TextEncoder().encode(JSON.stringify(batch)).byteLength <= C.maxBatchBytes);
const outbox = new PlayerDataOutbox(null); await outbox.open(); await outbox.put(batch);
let responseCopies = 1;
const transport = new PlayerDataTransport(outbox, { endpoint: 'http://127.0.0.1/test',
  fetch: async () => ({ ok: true, json: async () => ({ ok: true, copies: responseCopies, id: batch.id }) }),
  navigator: { sendBeacon: () => true } });
await transport.drain();
assert.equal((await outbox.list()).length, 1, 'one server copy is not a storage receipt');
transport.nextAttempt = 0; responseCopies = 2;
assert.equal(transport.beacon((await outbox.list())[0]), true);
assert.equal((await outbox.list()).length, 1, 'beacon never deletes the retry copy');
await transport.drain(); assert.equal((await outbox.list()).length, 0);
const offline = new PlayerDataTransport(outbox, { endpoint: 'http://127.0.0.1/test', fetch: async () => { throw new Error('offline'); } });
await outbox.put(batch); await offline.drain();
assert.equal((await outbox.list()).length, 1, 'offline data survives');
for (let n = 0; n < C.maxQueuedBatches + 10; n++) await outbox.put({ ...batch, id: crypto.randomUUID() });
assert.equal((await outbox.list()).length, C.maxQueuedBatches);
assert.ok(outbox.lost > 0);
console.log('PLAYER_DATA_CLIENT_CONTRACT_OK');
