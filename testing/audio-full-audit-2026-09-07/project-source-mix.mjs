import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { AUDIO_MASTERING as config } from '../../values/audioMastering.js';

const measurements = JSON.parse(await readFile(new URL('./measurements.json', import.meta.url), 'utf8'));
const playlist = new Set(JSON.parse(await readFile(new URL('../../sound/playlists/playlist.json', import.meta.url), 'utf8')));
assert.equal(measurements.flags.decodeErrors.length, 0, 'A complete decode is required');
const report = [];
for (const kind of ['music', 'voice']) {
  const lines = [];
  for (const row of measurements.items.filter(r => r.kind === kind && !r.families.includes('signal'))) {
    if (kind === 'music' && !playlist.has(row.path.split('/').pop())) continue;
    assert.ok(Number.isFinite(row.integratedLUFS) && row.integratedLUFS > -60, row.path);
    assert.ok(Number.isFinite(row.truePeakDbTP), row.path);
    const db = Math.min(config[`${kind}MaxBoostDb`], config[`${kind}TargetLufs`] - row.integratedLUFS,
      config.truePeakCeilingDb - row.truePeakDbTP);
    const gain = Math.floor(10 ** (db / 20) * 1e6) / 1e6;
    const mix = { gain };
    if (kind === 'voice') {
      const start = row.leadingSilenceSeconds > config.voiceSilenceThresholdSeconds
        ? row.leadingSilenceSeconds - config.voiceLeadingPadSeconds : 0;
      const trimEnd = row.trailingSilenceSeconds > config.voiceSilenceThresholdSeconds
        ? row.trailingSilenceSeconds - config.voiceTrailingPadSeconds : 0;
      if (start || trimEnd) mix.window = { start: +start.toFixed(3), duration: +(row.duration - start - trimEnd).toFixed(3),
        fadeIn: config.voiceFadeInSeconds, fadeOut: config.voiceFadeOutSeconds };
    }
    const key = kind === 'music' ? row.path.split('/').pop() : row.path;
    let value = `Object.freeze(${JSON.stringify(mix)})`;
    if (mix.window) value = `Object.freeze({gain:${gain},window:Object.freeze(${JSON.stringify(mix.window)})})`;
    lines.push(`  ${JSON.stringify(key)}: ${value},`);
    report.push({ path: row.path, sourceSha256: row.sha256, kind, beforeLufs: row.integratedLUFS,
      afterLufs: +(row.integratedLUFS + 20 * Math.log10(gain)).toFixed(3),
      afterTruePeakDbTP: +(row.truePeakDbTP + 20 * Math.log10(gain)).toFixed(3), ...mix });
  }
  const source = `// Generated by testing/audio-full-audit-2026-09-07/project-source-mix.mjs.\n`
    + `// Full-file FFmpeg measurements and source hashes are retained with that audit.\n`
    + `export const ${kind.toUpperCase()}_SOURCE_MIX = Object.freeze({\n${lines.join('\n')}\n});\n`;
  await writeFile(new URL(`../../values/${kind}SourceMix.generated.js`, import.meta.url), source);
}
await writeFile(new URL('./source-mix.json', import.meta.url), JSON.stringify({ config, items: report }, null, 2) + '\n');
console.log(JSON.stringify({ calibrated: report.length, trimmedVoices: report.filter(r => r.window).length,
  maxTruePeakDbTP: Math.max(...report.map(r => r.afterTruePeakDbTP)) }));
