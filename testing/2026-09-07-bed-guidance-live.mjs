  assert.equal(evidence.pausedAfter.elapsed, evidence.pausedBefore.elapsed);
  assert.equal(evidence.pausedAfter.arrowVisible, false);
  await page.keyboard.press('Escape'); await waitGuide();
  await page.keyboard.down('d');
  await page.waitForFunction(() => window.__phaserGame.scene.getScene('PlayScene').townRestSystem.isInRange(), null, { timeout: 20000 });
  await page.keyboard.up('d');
  await page.waitForTimeout(100);
