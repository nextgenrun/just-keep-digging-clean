  await page.waitForFunction(() => window.__phaserGame.scene.getScene('PlayScene').townRestSystem.guidance.phase === 'idle');
  evidence.ignored = await snap(); assert.equal(evidence.ignored.arrowVisible, false);
  console.log('BED_GUIDANCE_IGNORED_OK');

  await openPause(); await clickControl('SAVES', true);
  await page.waitForFunction(() => Boolean(window.__phaserGame.scene.getScene('PlayScene')._pausePanel?.state.saveTransfer));
  await page.waitForTimeout(250);
  const saveLabel = await page.evaluate(() => window.__phaserGame.scene.getScene('PlayScene')._pausePanel.state.controls[0].text.text);
  await clickControl(saveLabel); await waitGuide();
  await page.keyboard.down('d');
  await page.waitForFunction(() => window.__phaserGame.scene.getScene('PlayScene').townRestSystem.guidance.phase === 'following');
  await page.keyboard.up('d');
  await page.waitForTimeout(9200);
  evidence.following = await snap();
  assert.equal(evidence.following.phase, 'following'); assert.equal(evidence.following.arrowVisible, true);
  assert.equal(evidence.following.saves, 0);
  await page.screenshot({ path: path.join(output, '02-following-persists.png') });

  await openPause();
