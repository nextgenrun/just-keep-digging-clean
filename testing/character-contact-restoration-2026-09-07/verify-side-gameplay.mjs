// Save-disabled, real-input verification of the restored SIDE punches.
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import { spawn } from "node:child_process";
import net from "node:net";
import { fileURLToPath } from "node:url";
import { chromium } from "file:///C:/Users/Mila/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs";

const root = fileURLToPath(new URL("../../", import.meta.url));
const origin = "http://127.0.0.1:8197";
const output = path.join(root, "testing/character-contact-restoration-2026-09-07/live-side-combo");
await fs.mkdir(output, { recursive: true });
await fs.writeFile(path.join(output, "readme.md"), "# Legacy SIDE punch gameplay evidence\n\nGenerated by the adjacent dated live QA script using normal mouse and keyboard input in an isolated, save-disabled browser against the canonical serve.py. Moving cases prime the combo index to reach the two restored actions directly.\n");
assert.equal(await (await fetch(`${origin}/values/survivalUalPlayerAssetProfile.js`)).text(),
  await fs.readFile(path.join(root, "values/survivalUalPlayerAssetProfile.js"), "utf8"));
const evidence = { errors: [], cases: [] };
const browser = await chromium.launch({ headless: true,
  executablePath: "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe",
  args: ["--autoplay-policy=no-user-gesture-required"] });
let page;
try {
  for (const facing of (process.env.CONTACT_QA_FACING ? [process.env.CONTACT_QA_FACING] : ["right", "left"])) {
    const direction = facing === "right" ? 1 : -1;
    const toward = direction > 0 ? "d" : "a", away = direction > 0 ? "a" : "d";
    page = await browser.newPage({ viewport: { width: 1280, height: 720 }, deviceScaleFactor: 1 });
    page.on("pageerror", error => evidence.errors.push(error.message));
    page.on("console",m=>{if(m.type()==="error")console.log("BROWSER_ERROR",m.text().slice(0,250))});
    await page.goto(`${origin}/?jkd_e2e=1&collisionReview=1&cinematics=0&impactFacing=${facing}`, { waitUntil: "commit", timeout: 60000 });
    await page.waitForFunction(() => window.__phaserGame?.scene.isActive("MainMenuScene"), null, { timeout: 180000 });
    await page.evaluate(() => window.__phaserGame.scene.getScene("MainMenuScene").scene.start("WorldLoadScene", {
      saveSlot: 3, worldIdentity: "legacy-side-punch-review-20260906", isNewSave: true, tutorialChoice: "no",
    }));
    await page.waitForFunction(() => {
      const s = window.__phaserGame?.scene.getScene("PlayScene");
      return s?.playerController && s.worldRenderer?.created && s.gameState === "playing" && window.__jkdE2E;
    }, null, { timeout: 180000 });
    await page.evaluate(() => window.__jkdE2E.closeAll?.());
    await page.keyboard.press("F1");
    await page.waitForTimeout(400);
    // Use real movement input to set persistent keyboard aim for this facing.
    await page.keyboard.down(toward); await page.waitForTimeout(100);
    await page.keyboard.up(toward); await page.waitForTimeout(180);
    const setup = await page.evaluate(() => {
      const s = window.__phaserGame.scene.getScene("PlayScene"), profile = s.playerAssetProfile;
      const q = window.__legacyPunchQa = { starts: [], impacts: [], samples: [], allFrames: [], mode: "cycle",
        legacyKeys: [...new Set(profile.digSidewaysHitAnims)], sequence: [...profile.complexDigSideAnimationKeys] };
      s.player.on("animationstart", animation => {
        const stage = s.ualMiningComboSelector?.state;
        if (!profile.digAnims.includes(animation.key)) return;
        q.starts.push({ key: animation.key, at: s.time.now, mode: q.mode,
          stage: stage?.stageIndex, bodyX: s.playerController.physicsBody.x,
          vx: s.playerController.physicsBody.vx, flipX: s.player.flipX });
      });
      s.events.on("dig-impact-presented", impact => q.impacts.push({ key: impact.animationKey,
        contactFrame: impact.contactFrame, visibleFrame: impact.visibleFrame,
        mode: q.mode, authored: impact.authored, rawPoint: impact.rawPoint, targetTile: impact.targetTile }));
      s.events.on("postupdate", () => {
        const p = s.player, b = s.playerController.physicsBody, key = p.anims.currentAnim?.key;
        q.allFrames.push({key, sourceSize:p.frame.realWidth, frame:String(p.frame.name), expected:String(p.anims.currentFrame?.textureFrame)});
        if (!q.legacyKeys.includes(key) && !key?.includes("moving-side-dig")) return;
        const anchor = b.getVisualAnchor?.() || { x: b.x + b.w / 2, y: b.y + b.h };
        q.samples.push({ key, frame: p.frame.name, mode: q.mode,
          bodyX: b.x, bodyY: b.y, vx: b.vx, grounded: b.onGround,
          dx: p.x - anchor.x, dy: p.y - anchor.y,
          origin: [p.originX, p.originY], scale: [p.scaleX, p.scaleY],
          offset: p.getData("visualOffset"), flipX: p.flipX });
      });
      return { savesBlocked: s._saveWritesBlocked, sequence: q.sequence, legacyKeys: q.legacyKeys };
    });
    assert.equal(setup.savesBlocked, true);
    assert.equal(setup.sequence.length, 12);
    const target = await page.evaluate(direction => {
      const s = window.__phaserGame.scene.getScene("PlayScene"), tile = s.playerController.getPlayerTile();
      return { tx: tile.tx + direction, ty: tile.ty };
    }, direction);
    async function clickTarget() {
      // Hold the normal mining key through a cold deferred-pack load.
      await page.keyboard.down("f");
    }
    async function settle() {
      await page.waitForFunction(() => {
        const q = window.__legacyPunchQa, s = window.__phaserGame.scene.getScene("PlayScene");
        return s.time.now - q.starts.at(-1).at >= 1520;
      }, null, { timeout: 10000 });
    }
    if (facing === "left") await page.evaluate(async () => {
      const s=window.__phaserGame.scene.getScene("PlayScene");
      for(const key of window.__legacyPunchQa.sequence) await s.playerDeferredAnimationAssetController.ensureForAnimation(key);
    });
    console.log(`LEGACY_PUNCH_GAME_READY ${facing}`, setup.sequence.length);
    let wrapped = false;
    for (let attempt = 0; attempt < 30 && !wrapped; attempt++) {
      const index = await page.evaluate(() => window.__phaserGame.scene.getScene("PlayScene")
        .ualMiningComboSelector?.state?.nextStageIndex || 0);
      if (index === 10) await page.keyboard.down(toward);
      if (index === 10 || index === 11) await page.keyboard.press("Shift+F8");
      const count = await page.evaluate(() => window.__legacyPunchQa.starts.length);
      await clickTarget();
      await page.waitForFunction(count => window.__legacyPunchQa.starts.length > count, count, { timeout: 15000 });
      await page.keyboard.up("f");
      const start = await page.evaluate(() => window.__legacyPunchQa.starts.at(-1));
      assert.equal(start.key, setup.sequence[start.stage], "Cold-load action must show its selected pose");
      if (index === 10 || index === 11) {
        await page.waitForFunction(() => window.__phaserGame.scene.isPaused("PlayScene"), null, { timeout: 5000 });
        await page.screenshot({ path: path.join(output, `${facing}-${index === 10 ? "jab" : "cross"}-contact.png`) });
        await page.keyboard.press("F8");
      }
      wrapped = await page.evaluate(() => {
        const a = window.__legacyPunchQa.starts;
        return a.length > 1 && a.at(-2).stage === 11 && a.at(-1).stage === 0;
      });
      await settle();
    }
    await page.keyboard.up(toward);
    const cycle = await page.evaluate(() => window.__legacyPunchQa.starts.filter(s => s.mode === "cycle"));
    assert.ok(await page.evaluate(()=>window.__legacyPunchQa.allFrames.every(f=>f.sourceSize===512 && f.frame===f.expected)), "Every SIDE action and recovery uses the approved frame set");
    assert.equal(wrapped, true, "Complete SIDE chain must wrap to the first stage");
    assert.deepEqual([...new Set(cycle.map(s => s.stage))].sort((a,b)=>a-b), setup.sequence.map((_,i)=>i));
    for (let i=1; i<cycle.length; i++) {
      const expectedStage = cycle[i].at - cycle[i-1].at > 2000 ? 0 : (cycle[i-1].stage + 1) % 12;
      assert.equal(cycle[i].stage, expectedStage, "Keep the existing 2 second combo reset behavior");
    }
    const warmed = await page.evaluate(() => {
      const s = window.__phaserGame.scene.getScene("PlayScene");
      return window.__legacyPunchQa.legacyKeys.every(key => s.anims.exists(s.playerAssetProfile.movingSideDigAnimationMap[key]));
    });
    assert.equal(warmed, true, "original moving pack must be ready before first moving legacy punch");
    // Each fresh scene exercises one original punch while approaching the wall.
    for (const restored of [facing === "right" ? 0 : 1]) {
      await page.keyboard.press("F1");
      await page.waitForTimeout(300);
      await page.keyboard.down(away);
      await page.waitForTimeout(700);
      await page.keyboard.up(away);
      await page.waitForTimeout(200);
      await page.evaluate(({ restored, target, direction }) => {
        const s = window.__phaserGame.scene.getScene("PlayScene"), q = window.__legacyPunchQa;
        q.mode = `moving-${restored}`;
        s.ualMiningComboSelector.reset();
        for (let i = 0; i < 10 + restored; i++) s.ualMiningComboSelector.select({
          family: "complex-side", direction: direction > 0 ? "RIGHT" : "LEFT",
          animationKeys: q.sequence, fallback: q.sequence[0], targetTile: target, nowMs: s.time.now,
        });
      }, { restored, target, direction });
      const count = await page.evaluate(() => window.__legacyPunchQa.starts.length);
      await page.keyboard.down(toward);
      await page.waitForFunction(direction => {
        const p = window.__phaserGame.scene.getScene("PlayScene").playerController;
        return p.isGrounded() && p.physicsBody.vx * direction > 20
          && p.getMotionState() === (direction > 0 ? "walk-right" : "walk-left");
      }, direction, { timeout: 3000 });
      const ready = await page.evaluate(async ({ restored, direction }) => {
        const s = window.__phaserGame.scene.getScene("PlayScene"), p = s.playerController;
        const { resolveMovingSideDigAnimation } = await import("/player/UalMovingSideDigSelector.js");
        const result = resolveMovingSideDigAnimation({ profile: s.playerAssetProfile,
          animationKey: window.__legacyPunchQa.legacyKeys[restored], aim: direction > 0 ? "RIGHT" : "LEFT",
          actionKind: "normal", grounded: p.isGrounded(), motionState: p.getMotionState(),
          horizontalVelocity: p.physicsBody.vx, currentAnimationKey: s.player.anims.currentAnim?.key,
          currentFrameIndex: s.player.anims.currentFrame?.index,
          currentTextureFrame: Number(s.player.anims.currentFrame?.textureFrame) });
        return { ...result, registered: s.anims.exists(result.animationKey), x: p.physicsBody.x,
          vx: p.physicsBody.vx, motion: p.getMotionState() };
      }, { restored, direction });
      console.log("MOVING_PUNCH_INPUT_READY", JSON.stringify(ready));
      assert.equal(ready.movingSideDigActive, true);
      assert.equal(ready.registered, true);
      await page.keyboard.down("f");
      await page.waitForFunction(count => window.__legacyPunchQa.starts.length > count, count, { timeout: 5000 });
      await page.keyboard.up("f");
      await page.waitForTimeout(600);
      await page.keyboard.up(toward);
      await settle();
      const start = await page.evaluate(() => window.__legacyPunchQa.starts.at(-1));
      assert.equal(start.stage, 10 + restored);
      assert.match(start.key, /moving-side-dig/);
    }
    const trace = await page.evaluate(() => window.__legacyPunchQa);
    for (const key of setup.legacyKeys) {
      const frames = trace.samples.filter(s => s.key === key && s.mode === "cycle");
      assert.ok(frames.length > 5, `missing gameplay frames for ${key}`);
      for (const sample of frames) {
        assert.ok(Math.abs(sample.dx) < 0.01, `horizontal sprite drift: ${JSON.stringify(sample)}`);
        assert.ok(Math.abs(sample.dy - frames[0].dy) < 0.01, `vertical sprite drift: ${JSON.stringify(sample)}`);
        assert.ok(Math.abs(sample.bodyX - frames[0].bodyX) < 0.01, "wall pressure moved body");
        assert.deepEqual(sample.scale, frames[0].scale, "per-frame scale drift");
        assert.deepEqual(sample.origin, frames[0].origin, "per-frame origin drift");
        assert.equal(sample.flipX, direction < 0, "restored punch facing");
        assert.ok(!sample.offset?.x && !sample.offset?.y, "contact alignment moved the sprite");
      }
      assert.ok(trace.impacts.some(impact => impact.key === key), `missing real impact for ${key}`);
    }
    for (const sample of trace.samples.filter(s => s.mode.startsWith("moving"))) {
      assert.ok(Math.abs(sample.dx) < 0.01, "moving sprite separated from body");
      const first = trace.samples.find(s => s.key === sample.key && s.mode === sample.mode);
      assert.ok(Math.abs(sample.dy - first.dy) < 0.01, "moving vertical anchor drift");
      assert.deepEqual(sample.scale, first.scale, "moving scale drift");
      assert.deepEqual(sample.origin, first.origin, "moving origin drift");
      assert.equal(sample.flipX, direction < 0, "moving punch facing");
      assert.ok(!sample.offset?.x && !sample.offset?.y, "moving contact offset");
    }
    assert.ok(trace.impacts.every(i=>i.authored), "Every real impact uses its authored extremity");
    evidence.cases.push({ facing, ...trace });
    console.log(`LEGACY_PUNCH_GAMEPLAY_OK ${facing}`, JSON.stringify({ starts: trace.starts.length,
      legacyFrames: trace.samples.length, impacts: trace.impacts.length,
      moving: trace.starts.filter(s => s.mode.startsWith("moving")).map(s => s.key) }));
    await page.close();
  }
  assert.deepEqual(evidence.errors, []);
  console.log("LEGACY_PUNCH_LIVE_QA_OK");
} catch (error) {
  evidence.failure = error.stack;
  if (page && !page.isClosed()) {
    evidence.lastState = await page.evaluate(() => {
      const s = window.__phaserGame?.scene.getScene("PlayScene"), p = s?.playerController;
      return { ...window.__legacyPunchQa, runtime: { gameState: s?.gameState, digAnimating: s?.isDigAnimating,
        scenePaused: s?.scene.isPaused(), motion: p?.getMotionState(), bodyX: p?.physicsBody.x,
        bodyY: p?.physicsBody.y, vx: p?.physicsBody.vx, aim: p?.input.getAimVector(),
        target: p?.getAimTargetTile(), selector: s?.ualMiningComboSelector?.state,
        animation: s?.player.anims.currentAnim?.key, playing: s?.player.anims.isPlaying } };
    }).catch(() => null);
    await page.screenshot({ path: path.join(output, "failure.png") }).catch(() => {});
  }
  throw error;
} finally {
  await fs.writeFile(path.join(output, process.env.CONTACT_QA_FACING ? `evidence-${process.env.CONTACT_QA_FACING}.json` : "evidence.json"), JSON.stringify(evidence, null, 2));
  await browser.close();

}
