import assert from 'node:assert/strict';
import { PhaserSessionObserver } from '../ui/telemetry/PhaserSessionObserver.js';
import { BrowserSessionInputs } from '../systems/telemetry/BrowserSessionInputs.js';
import { SessionRecorder } from '../systems/telemetry/SessionRecorder.js';
const recorded = [];
const observer = Object.create(PhaserSessionObserver.prototype);
Object.assign(observer, { objects: new WeakMap(), disposers: [], service: { record: (...args) => recorded.push(args) } });
const proto = { run(value) { return { owner: this, value }; } };
const object = Object.create(proto);
observer.observe(object, 'run', 'result', (_args, result) => ({ value: result.value }));
const result = object.run(7);
assert.equal(result.owner, object); assert.equal(result.value, 7);
const promise = Promise.resolve({ success: true });
const asyncObject = { run: () => promise };
observer.observe(asyncObject, 'run', 'result', () => ({ success: true }));
assert.equal(asyncObject.run(), promise, 'observer changed promise identity');
const error = new Error('original');
const throwing = { run() { throw error; } };
observer.observe(throwing, 'run', 'result', () => ({}));
assert.throws(() => throwing.run(), value => value === error);
const before = object.run;
observer.observe(object, 'run', 'result', () => ({}));
assert.equal(object.run, before, 'duplicate observation replaced a wrapper');
observer.destroy();
assert.equal(Object.hasOwn(object, 'run'), false, 'prototype method not restored');
assert.equal(object.run, proto.run);
let now = 0;
const recorder = new SessionRecorder({ now: () => now });
recorder.setState({ phase: 'gameplay', scene: 'PlayScene' });
const service = { enabled: true, recorder, record: (...args) => recorder.record(...args), flush: async () => {}, setEnabled: async () => {} };
const inputs = Object.create(BrowserSessionInputs.prototype);
Object.assign(inputs, { service, keys: new Map(), resolveAction: () => 'moveLeft' });
const target = { isContentEditable: false, closest: () => null };
const event = { code: 'KeyA', target, preventDefault() { throw new Error('input was consumed'); },
  stopPropagation() { throw new Error('input was consumed'); } };
inputs.keyboard(event, true); now = 400; inputs.keyboard(event, false);
const up = recorder.events.find(event => event.type === 'input_up');
assert.equal(up.detail.heldMs, 400); assert.equal(up.detail.action, 'moveLeft');
const count = recorder.events.length;
inputs.keyboard({ ...event, code: 'KeyP', target: { ...target, isContentEditable: true } }, true);
assert.equal(recorder.events.length, count, 'text input was recorded');
recorder.setState({ phase: 'menu' });
const menuCount = recorder.events.length;
inputs.keyboard({ ...event, code: 'KeyP' }, true);
assert.equal(recorder.events.length, menuCount, 'free menu text was recorded');
await promise;
console.log('PLAYER_DATA_OBSERVER_CONTRACT_OK');
