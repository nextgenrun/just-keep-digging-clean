// Generate a small, resumable, credential-free-on-disk Signal voice library.
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { SIGNAL_SURVIVORS } from "../values/signalSurvivors.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const folder = path.join(root, "sound/voice-lines/signal-v1");
const manifestPath = path.join(folder, "manifest.json");
const model = "x-ai/grok-voice-tts-1.0";
function mp3Duration(bytes) {
  let seconds = 0;
  for (let i = 0; i < bytes.length - 4;) {
    if (bytes[i] !== 255 || (bytes[i + 1] & 224) !== 224) { i++; continue; }
    const version = (bytes[i + 1] >> 3) & 3, layer = (bytes[i + 1] >> 1) & 3;
    const bitrateIndex = bytes[i + 2] >> 4, rateIndex = (bytes[i + 2] >> 2) & 3;
    if (version === 1 || layer !== 1 || !bitrateIndex || bitrateIndex === 15 || rateIndex === 3) { i++; continue; }
    const rates = version === 3 ? [0,32,40,48,56,64,80,96,112,128,160,192,224,256,320] : [0,8,16,24,32,40,48,56,64,80,96,112,128,144,160];
    const hz = [44100,48000,32000][rateIndex] / (version === 3 ? 1 : version === 2 ? 2 : 4);
    const size = Math.floor((version === 3 ? 144000 : 72000) * rates[bitrateIndex] / hz) + ((bytes[i + 2] >> 1) & 1);
    if (i + size > bytes.length) break;
    seconds += (version === 3 ? 1152 : 576) / hz; i += size;
  }
  if (!(seconds > 0)) throw new Error("Cannot measure MP3 duration.");
  return seconds;
}
const clips = SIGNAL_SURVIVORS.filter(s => s.kind !== "dog").flatMap(s => Object.entries(s.lines).map(([kind, text]) => ({
  id: `${s.id}-${kind}`, survivor: s.id, voice: s.voice, kind, text,
})));
const characters = clips.reduce((sum, c) => sum + c.text.length, 0);
if (clips.length > 36 || characters * 0.000015 > 0.25) throw new Error("Signal batch exceeds its local spending cap.");
await fs.mkdir(folder, { recursive: true });
await fs.writeFile(path.join(folder, "readme.md"), "# Signal voices\n\nShort authored survivor speech, generated through OpenRouter. Captions use the exact input scripts in values/signalSurvivors.js. No runtime API calls or credentials. manifest.json records source hashes and measured durations.\n");
let manifest = { model, generatedAt: new Date().toISOString(), estimatedCostUsd: characters * 0.000015, clips: {} };
try { manifest = JSON.parse(await fs.readFile(manifestPath, "utf8")); } catch {}
const apiKey = process.env.SIGNAL_TTS_KEY;
if (!apiKey) throw new Error("Set SIGNAL_TTS_KEY in this process before running generation.");
console.log(`Signal: ${clips.length} clips; ${characters} characters; estimated $${(characters * 0.000015).toFixed(4)}.`);
for (const clip of clips) {
  const hash = createHash("sha256").update(JSON.stringify({ model, ...clip })).digest("hex");
  const dest = path.join(folder, `${clip.id}.mp3`);
  if (manifest.clips[clip.id]?.sourceHash === hash && await fs.stat(dest).then(s => s.size > 1000).catch(() => false)) continue;
  const input = ["farA", "farB", "middle"].includes(clip.kind) ? `[shouting] ${clip.text}` : clip.text;
  const response = await fetch("https://openrouter.ai/api/v1/audio/speech", {
    method: "POST", signal: AbortSignal.timeout(45000),
    headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
    body: JSON.stringify({ model, voice: clip.voice, input, response_format: "mp3" }),
  });
  if (!response.ok) {
    console.error(`Signal speech stopped at ${clip.id}: HTTP ${response.status}. No credentials or provider body logged.`);
    process.exitCode = 1; break;
  }
  const audio = Buffer.from(await response.arrayBuffer());
  if (audio.length < 1000 || !/audio|octet-stream/.test(response.headers.get("content-type") || "")) throw new Error("Provider did not return valid audio.");
  await fs.writeFile(dest, audio);
  const duration = mp3Duration(audio);
  manifest.clips[clip.id] = { ...clip, path: `sound/voice-lines/signal-v1/${clip.id}.mp3`, durationMs: Math.ceil(duration * 1000), sourceHash: hash, bytes: audio.length };
  await fs.writeFile(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
  console.log(`${clip.id}: ${duration.toFixed(2)}s`);
}
await fs.writeFile(path.join(root, "values/signalVoiceManifest.generated.js"), `// Generated by ai-tools/2026-09-07-generate-signal-voices.mjs. No credentials.\nexport const SIGNAL_VOICE_CLIPS = Object.freeze(${JSON.stringify(manifest.clips, null, 2)});\n`);
console.log(`Saved ${Object.keys(manifest.clips).length}/${clips.length} clips.`);
